def canonical_chapter(label: str) -> str:
    """Map one raw chapter label to its canonical form."""
    if not isinstance(label, str):
        return label
    key = label.strip().lower()
    if key in ALIASES:
        return ALIASES[key]
    # fallback: Title-Case the stripped label (collapses case-dups when
    # combined with frequency choice in canonicalize()).
    return label.strip()


def canonicalize(labels: list[str]) -> list[str]:
    """Dedupe (case-insensitive) + canonicalize, preserving order."""
    seen: dict[str, str] = {}
    for lab in labels or []:
        canon = canonical_chapter(lab)
        key = canon.strip().lower()
        if key not in seen:
            seen[key] = canon.strip()
    return list(seen.values())
